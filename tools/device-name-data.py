#!/usr/bin/env python3
"""Maintain external ACPI names and feed their captions to Qt lupdate."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "resources/external/device-names"


def read_names(path):
    names = {}
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        fields = line.split("\t")
        if (len(fields) != 2 or not re.fullmatch(r"[A-Z0-9_]{3,32}", fields[0])
                or not fields[1].strip() or fields[0] in names):
            raise ValueError(f"{path}:{number}: invalid or duplicate entry")
        names[fields[0]] = fields[1]
    return names


def import_acpica(args):
    raw = args.source.read_bytes()
    if len(raw) > 65536 or not re.fullmatch(r"[0-9a-f]{40}", args.revision):
        raise ValueError("Expected a bounded ACPICA source and an exact Git revision")
    source = raw.decode("utf-8")
    # Accept only this known data table, not arbitrary C syntax or expressions.
    marker = "const AH_DEVICE_ID  AslDeviceIds[] =\n{"
    if source.count(marker) != 1:
        raise ValueError("ACPICA table declaration changed; review the importer")
    table = source.split(marker, 1)[1].split("};", 1)[0]
    if table.count("{NULL, NULL}") != 1 or table.split("{NULL, NULL}", 1)[1].strip():
        raise ValueError("ACPICA table terminator changed")
    names = {}
    for line in table.split("{NULL, NULL}", 1)[0].splitlines():
        if not line.strip():
            continue
        match = re.fullmatch(r'\s*\{"([A-Z0-9_]{3,32})",\s*"([^"\\\t]+)"\},\s*', line)
        if not match or match[1] in names:
            raise ValueError(f"Unrecognized or duplicate ACPICA entry: {line}")
        names[match[1]] = match[2]
    if not 100 <= len(names) <= 4096:
        raise ValueError("Unexpected ACPICA database size")
    overrides = read_names(DATA / "overrides.tsv")
    names.update(overrides)
    license_text = args.license.read_text(encoding="utf-8")
    if "SPDX-License-Identifier: BSD-3-Clause" not in license_text:
        raise ValueError("Expected ACPICA's BSD-3-Clause license")
    header = (f"# ACPICA source/common/ahids.c, revision {args.revision}\n"
              f"# https://github.com/open-acpica/acpica/blob/{args.revision}/source/common/ahids.c\n"
              f"# Source SHA256: {hashlib.sha256(raw).hexdigest()}\n"
              "# Generated by tools/device-name-data.py; local overrides applied.\n"
              "# Format: ID<TAB>description; blank lines and # comments allowed.\n")
    header += "".join(("# " + line).rstrip() + "\n" for line in license_text.splitlines())
    output = header + "\n" + "".join(key + "\t" + names[key] + "\n" for key in sorted(names))
    args.output.write_text(output, encoding="utf-8")
    print(f"Wrote {len(names)} names ({len(overrides)} local captions/overrides)")


def translations(args):
    names = read_names(DATA / "acpi-pnp.ids")
    # Temporary extraction input only: no generated table is compiled or checked in.
    with tempfile.TemporaryDirectory() as folder:
        path = Path(folder) / "device-name-captions.cpp"
        path.write_text("".join('QT_TRANSLATE_NOOP("DeviceFunctions", '
                        + json.dumps(label, ensure_ascii=False) + ');\n'
                        for label in sorted(set(names.values()))), encoding="utf-8")
        subprocess.run([args.lupdate, str(ROOT / "src"), str(path),
                        "-locations", "none", "-ts", str(ROOT /
                        "resources/external/translations/qlinuxdevicemanager_en.ts")], check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    update = sub.add_parser("import-acpica")
    update.add_argument("source", type=Path)
    update.add_argument("--revision", required=True)
    update.add_argument("--license", type=Path, required=True)
    update.add_argument("--output", type=Path, default=DATA / "acpi-pnp.ids")
    update.set_defaults(run=import_acpica)
    translate = sub.add_parser("translations")
    translate.add_argument("--lupdate", required=True)
    translate.set_defaults(run=translations)
    args = parser.parse_args()
    args.run(args)


if __name__ == "__main__":
    main()
